def check(name,condition):
    checks.append({'check':name,'pass':bool(condition)})
    if not condition: raise AssertionError(name)
def shot(page,name):
    page.screenshot(path=str(SHOTS/name),full_page=True)
def snap(page):return page.evaluate('B2Game.snapshot()')
def rec(page,id):return snap(page)['records'][id]
def fill(page,id,text):
    page.locator('#'+id).fill(str(text))
    if id.startswith('hours-'): page.locator('#'+id).blur()
def skip_to_practice(page):
    page.get_by_role('button',name='Start guided route',exact=False).click()
