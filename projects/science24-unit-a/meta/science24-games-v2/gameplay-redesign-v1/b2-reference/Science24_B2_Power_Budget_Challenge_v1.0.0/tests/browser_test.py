def lighting(page):
    page.locator('#option-lights').select_option('led');fill(page,'hours-lights',6)
    page.locator('#choice-same-service').check();fill(page,'total','.360');submit(page)
def computers(page):
    for id,h in [('computers',2),('lights',3),('fan',2)]:fill(page,'hours-'+id,h)
    page.locator('#choice-all').check();fill(page,'total','1.616');submit(page)
def projector(page):
    page.locator('#option-projector').select_option('b');page.locator('#choice-time').check()
    fill(page,'total','0.369');fill(page,'explanation','I kept the full 90-minute projection and all four hours of lighting, using the equivalent 150 W projector.');submit(page)
def efficient(page):
    fill(page,'percent','60');fill(page,'other','600');page.locator('#choice-no').check()
    page.get_by_role('button',name='Check energy account',exact=False).click()
def progress_to_transfer(page):
    skip_to_practice(page);lighting(page);next_step(page);computers(page);next_step(page);projector(page);next_step(page);efficient(page);next_step(page)
def transfer(page,initial='.780',revised='.580'):
    fill(page,'initial',initial);fill(page,'revised',revised);page.locator('#choice-replace').check()
    fill(page,'explanation','The four lights use 0.180 kWh. Two 80 W workstations for 2.5 h use 0.400 kWh. The total is 0.580 kWh, below 0.650 kWh, with all service times unchanged.')
    page.get_by_role('button',name='Submit independent answer',exact=False).click()

