import path from "node:path";

import type { EmbeddedAssetRecord } from "./exports/shared.js";

export type AppsScriptDriveAssetManifestEntry = {
  id: string;
  relativePath: string;
  mimeType: string;
  contentKind: EmbeddedAssetRecord["contentKind"];
  serveMode: "apps-script" | "drive";
  referencePath?: string;
  byteSize?: number;
  bootstrapInline?: boolean;
};

export type AppsScriptDriveAssetManifest = {
  shellAssetPath: string;
  assets: AppsScriptDriveAssetManifestEntry[];
};

export const APPS_SCRIPT_DRIVE_ASSET_DIR = "drive-assets";
export const APPS_SCRIPT_SHELL_ASSET_PATH = "__canvas_helper_shell/index.html";
export const APPS_SCRIPT_ASSET_MANIFEST_PATH = "asset-manifest.json";
const APPS_SCRIPT_BOOTSTRAP_INLINE_TEXT_ASSET_MAX_BYTES = 64 * 1024;
const APPS_SCRIPT_BOOTSTRAP_INLINE_TEXT_ASSET_MIME_TYPES = new Set([
  "text/html",
  "text/css",
  "text/javascript",
  "application/javascript",
  "application/json",
  "text/json",
  "image/svg+xml"
]);

function shouldBootstrapInlineTextAsset(record: EmbeddedAssetRecord, byteSize: number) {
  if (record.contentKind !== "text") {
    return false;
  }

  if (record.referencePath && record.mimeType.toLowerCase() !== "image/svg+xml") {
    return false;
  }

  if (byteSize > APPS_SCRIPT_BOOTSTRAP_INLINE_TEXT_ASSET_MAX_BYTES) {
    return false;
  }

  return APPS_SCRIPT_BOOTSTRAP_INLINE_TEXT_ASSET_MIME_TYPES.has(record.mimeType.toLowerCase());
}

function extensionForAsset(record: EmbeddedAssetRecord) {
  if (record.contentKind === "file") {
    const sourceExtension = path.extname(record.sourcePath);
    if (sourceExtension) {
      return sourceExtension;
    }
  }

  switch (record.mimeType) {
    case "text/html":
      return ".html";
    case "text/css":
      return ".css";
    case "text/javascript":
    case "application/javascript":
      return ".js";
    case "application/json":
    case "text/json":
      return ".json";
    case "application/pdf":
      return ".pdf";
    case "image/svg+xml":
      return ".svg";
    case "image/png":
      return ".png";
    case "image/jpeg":
      return ".jpg";
    case "image/webp":
      return ".webp";
    case "image/gif":
      return ".gif";
    case "video/mp4":
      return ".mp4";
    case "audio/mpeg":
      return ".mp3";
    default:
      return ".bin";
  }
}

function buildAssetRelativePath(record: EmbeddedAssetRecord) {
  const bucket = record.contentKind === "text" ? "text-assets" : "binary-assets";
  return `${bucket}/${record.id}${extensionForAsset(record)}`;
}

export function buildAppsScriptAssetManifest(documentAssets: Array<EmbeddedAssetRecord>): AppsScriptDriveAssetManifest {
  return {
    shellAssetPath: APPS_SCRIPT_SHELL_ASSET_PATH,
    assets: documentAssets.map((record) => {
      const byteSize = record.contentKind === "text" ? Buffer.byteLength(record.textContent, "utf8") : undefined;
      return {
        id: record.id,
        relativePath: buildAssetRelativePath(record),
        mimeType: record.mimeType,
        contentKind: record.contentKind,
        serveMode: record.contentKind === "text" ? "apps-script" : "drive",
        ...(record.referencePath ? { referencePath: record.referencePath } : {}),
        ...(typeof byteSize === "number" ? { byteSize } : {}),
        ...(typeof byteSize === "number" && shouldBootstrapInlineTextAsset(record, byteSize)
          ? { bootstrapInline: true }
          : {})
      };
    })
  };
}

