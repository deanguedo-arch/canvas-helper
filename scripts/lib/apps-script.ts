function removeAppsScriptLinesBetween_(lines: string[], startLine: string, endLine: string) {
  const startIndex = lines.indexOf(startLine);
  const endIndex = lines.indexOf(endLine);
  if (startIndex < 0 || endIndex < 0 || endIndex <= startIndex) {
    return lines;
  }

  return [...lines.slice(0, startIndex), ...lines.slice(endIndex)];
}

